let currentLang = 'es';

function toggleLang() {
  currentLang = currentLang === 'es' ? 'en' : 'es';
  document.getElementById('lang-label').textContent = currentLang.toUpperCase();
  applyTranslations(currentLang);
}

function applyTranslations(lang) {
  const t = translations[lang];

  const ids = [
    // Navbar
    'nav-congreso','nav-memoria','nav-aliados','nav-prensa','nav-marketplace','nav-colabora','nav-asistir',
    'nav-mob-congreso','nav-mob-memoria','nav-mob-aliados','nav-mob-prensa','nav-mob-marketplace','nav-mob-colabora','nav-mob-asistir',
    // Contenido
    'page-title',
    'intro-p1','intro-p2',
    'item-1-title','item-1-desc',
    'item-2-title','item-2-desc',
    'item-3-title','item-3-desc',
    'item-4-title','item-4-desc',
    'item-5-title','item-5-desc',
    'item-6-title','item-6-desc',
    'item-7-title','item-7-desc',
    'item-8-title','item-8-desc',
    'item-9-title','item-9-desc',
    'item-10-title','item-10-desc',
    'item-11-title','item-11-desc',
    'closing-p1','closing-p2','closing-p3',
    // Footer
    'footer-escribenos','footer-escribenos-desc',
    'footer-email-label','footer-msg-label','footer-send',
    'footer-contact','footer-streaming','footer-redes',
    'footer-privacy','footer-cookies','footer-legal','footer-convivencia',
  ];

  ids.forEach(id => {
    const el = document.getElementById(id);
    if (el && t[id] !== undefined) el.innerHTML = t[id];
  });

  // Placeholders (atributo, no innerHTML)
  const placeholders = {
    'footer-email-input': 'footer-email-placeholder',
    'footer-msg-input':   'footer-msg-placeholder',
  };
  Object.entries(placeholders).forEach(([elId, key]) => {
    const el = document.getElementById(elId);
    if (el && t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });
}