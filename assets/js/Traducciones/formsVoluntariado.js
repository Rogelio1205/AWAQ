let currentLang = 'es';

function toggleLang() {
  currentLang = currentLang === 'es' ? 'en' : 'es';
  document.getElementById('lang-label').textContent = currentLang.toUpperCase();
  applyTranslations(currentLang);
}

function applyTranslations(lang) {
  const t = translations[lang];

  // innerHTML ids
  const htmlIds = [
    'nav-congreso','nav-memoria','nav-aliados','nav-prensa','nav-marketplace','nav-colabora','nav-asistir',
    'nav-mob-congreso','nav-mob-memoria','nav-mob-aliados','nav-mob-prensa','nav-mob-marketplace','nav-mob-colabora','nav-mob-asistir',
    'page-title','page-subtitle','page-disclaimer',
    'form-title','form-subtitle',
    'label-nombre','label-apellidos','label-email','label-telefono','label-pais',
    'label-org','label-cargo','label-linkedin','label-area',
    'label-disp','label-zona','label-exp','label-motiv',
    'label-opcional1','label-opcional2','label-opcional3','label-opcional4','label-opcional5',
    'country-label','state-label','city-label',
    'terms-label','newsletter-label',
    'btn-enviar-text','btn-volver','validation-msg',
    'modal-title','modal-desc','modal-btn',
    'footer-escribenos','footer-escribenos-desc','footer-email-label','footer-msg-label',
    'footer-send','footer-contact','footer-streaming',
    'footer-privacy','footer-cookies','footer-legal','footer-convivencia',
  ];

  htmlIds.forEach(id => {
    const el = document.getElementById(id);
    if (el && t[id] !== undefined) el.innerHTML = t[id];
  });

  // Select option texts
  const optionIds = [
    'area-placeholder','area-comunicaciones','area-marketing','area-ingenieria','area-otros',
    'disp-placeholder','disp-1','disp-2','disp-3','disp-4','disp-5',
    'zona-placeholder','zona-otra',
  ];
  optionIds.forEach(id => {
    const el = document.getElementById(id);
    if (el && t[id] !== undefined) el.textContent = t[id];
  });

  // Input placeholders
  const placeholders = {
    'input-nombre':   lang === 'es' ? 'Ingresa tu nombre'        : 'Enter your first name',
    'input-apellidos':lang === 'es' ? 'Ingresa tus apellidos'    : 'Enter your last name',
    'input-email':    lang === 'es' ? 'ejemplo@correo.com'       : 'example@email.com',
    'phone-input':    '000 000 0000',
    'input-org':      lang === 'es' ? 'Nombre de tu organización': 'Your organization name',
    'input-cargo':    lang === 'es' ? 'Tu cargo o perfil actual' : 'Your current role or profile',
    'input-linkedin': 'https://linkedin.com/in/usuario',
    'input-exp':      lang === 'es'
      ? 'Describe brevemente tu experiencia relevante para el voluntariado virtual.'
      : 'Briefly describe your relevant experience for virtual volunteering.',
    'input-motiv':    lang === 'es'
      ? 'Cuéntanos por qué quieres ser parte del voluntariado virtual del 3ICEO LATAM 2027.'
      : 'Tell us why you want to be part of the 3ICEO LATAM 2027 virtual volunteering team.',
    'footer-email-placeholder': lang === 'es' ? 'correo@electrónico.com' : 'email@example.com',
    'footer-msg-placeholder':   lang === 'es' ? 'Click para empezar a escribir' : 'Click to start writing',
    'country-search': lang === 'es' ? 'Buscar país...'   : 'Search country...',
    'state-search':   lang === 'es' ? 'Buscar región...' : 'Search region...',
    'city-search':    lang === 'es' ? 'Buscar ciudad...' : 'Search city...',
    'phone-search':   lang === 'es' ? 'Buscar país...'   : 'Search country...',
  };
  Object.entries(placeholders).forEach(([id, text]) => {
    const el = document.getElementById(id);
    if (el) el.setAttribute('placeholder', text);
  });
}